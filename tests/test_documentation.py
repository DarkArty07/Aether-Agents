def test_rejects_unsafe_or_missing_traceability_path(tmp_path: Path) -> None:
    root = _repository(tmp_path)
    registry = (root / "docs/capabilities.toml").read_text(encoding="utf-8")
    (root / "docs/capabilities.toml").write_text(
        registry.replace('"docs/current.md"', '"../outside.md"'), encoding="utf-8"
    )

    unsafe = _run(root, "--write")
    assert unsafe.returncode == 1
    assert "unsafe project-relative path" in unsafe.stderr

    (root / "docs/capabilities.toml").write_text(
        registry.replace('"docs/current.md"', '"docs/missing.md"'), encoding="utf-8"
    )
    missing = _run(root, "--write")
    assert missing.returncode == 1
    assert "missing or non-regular path: docs/missing.md" in missing.stderr


