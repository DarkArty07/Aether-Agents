from __future__ import annotations

import subprocess
import sys
import tomllib
from pathlib import Path

ROOT = Path(__file__).parents[1]
CHECKER = ROOT / "scripts" / "check_documentation.py"


def _run(root: Path, *arguments: str) -> subprocess.CompletedProcess[str]:
    return subprocess.run(
        [sys.executable, str(CHECKER), "--root", str(root), *arguments],
        check=False,
        capture_output=True,
        text=True,
    )


def _write(path: Path, content: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(content, encoding="utf-8")


def _registry(
    *, surfaces: list[str], status: str = "implemented", verification: str = '"tests/test_cli.py"'
) -> str:
    rendered_surfaces = ", ".join(f'"{surface}"' for surface in surfaces)
    return f'''schema_version = 1
generated_reference = "docs/reference/capabilities.md"

[[capabilities]]
id = "sample"
status = "{status}"
summary = "Sample capability."
surfaces = [{rendered_surfaces}]
documents = ["docs/current.md"]
specifications = ["specs/spec.md"]
implementation = ["src/aether_agents/cli.py"]
verification = [{verification}]
notes = ""
'''


def _derived_surfaces() -> list[str]:
    return [
        "cli.command.aether",
        "cli.command.aether.alpha",
        "cli.option.aether.--version",
        "cli.option.aether.alpha.--flag",
        "cli.argument.aether.alpha.target",
        "plugin.sample-plugin",
        "tool.sample_tool",
        "tool_action.sample_tool.status",
        "tool_action.sample_tool.validate",
        "role.morfeo",
    ]


def _repository(tmp_path: Path, *, registry: str | None = None) -> Path:
    _write(tmp_path / "src/aether_agents/__init__.py", "")
    _write(
        tmp_path / "src/aether_agents/cli.py",
        """import argparse


def _build_parser():
    parser = argparse.ArgumentParser(prog="aether")
    parser.add_argument("--version", action="store_true")
    subparsers = parser.add_subparsers(dest="command")
    alpha = subparsers.add_parser("alpha")
    alpha.add_argument("target")
    alpha.add_argument("--flag", action="store_true")
    return parser
""",
    )
    _write(
        tmp_path / "src/aether_agents/plugins/hermes_plugin.py",
        """_ACTIONS = ("status", "validate")


def register(ctx):
    ctx.register_tool(
        name="sample_tool",
        schema={
            "parameters": {
                "properties": {"action": {"enum": list(_ACTIONS)}},
            },
        },
    )
""",
    )
    _write(
        tmp_path / "pyproject.toml",
        """[project]
name = "sample"

[project.entry-points."hermes_agent.plugins"]
sample-plugin = "aether_agents.plugins.hermes_plugin"
""",
    )
    _write(tmp_path / "src/aether_agents/resources/profiles/morfeo/config.yaml", "plugins: {}\n")
    _write(tmp_path / "docs/current.md", "# Current documentation\n")
    _write(tmp_path / "specs/spec.md", "# Specification\n")
    _write(tmp_path / "tests/test_cli.py", "def test_placeholder():\n    assert True\n")
    _write(
        tmp_path / "docs/capabilities.toml",
        registry or _registry(surfaces=_derived_surfaces()),
    )
    return tmp_path


def test_write_then_check_is_deterministic_and_check_does_not_mutate(tmp_path: Path) -> None:
    root = _repository(tmp_path)

    written = _run(root, "--write")
    assert written.returncode == 0, written.stderr
    generated = root / "docs/reference/capabilities.md"
    first = generated.read_bytes()
    assert first.startswith(b"<!-- Generated by scripts/check_documentation.py; do not edit. -->\n")
    assert b"# Capability coverage\n" in first
    assert b"[capability registry](../capabilities.toml)" in first

    checked = _run(root)
    assert checked.returncode == 0, checked.stderr
    assert generated.read_bytes() == first

    rewritten = _run(root, "--write")
    assert rewritten.returncode == 0, rewritten.stderr
    assert generated.read_bytes() == first


def test_rejects_missing_derived_cli_command_and_tool_action(tmp_path: Path) -> None:
    surfaces = _derived_surfaces()
    root = _repository(
        tmp_path,
        registry=_registry(
            surfaces=[
                surface
                for surface in surfaces
                if surface not in {"cli.command.aether.alpha", "tool_action.sample_tool.validate"}
            ]
        ),
    )

    completed = _run(root, "--write")

    assert completed.returncode == 1
    assert "uncovered derived surface: cli.command.aether.alpha" in completed.stderr
    assert "uncovered derived surface: tool_action.sample_tool.validate" in completed.stderr


